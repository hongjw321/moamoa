-- MOAMOA 중앙 관리자 보안 이벤트
-- Supabase SQL Editor에서 1회 실행하세요.
create table if not exists public.admin_security_events (
  id bigint generated by default as identity primary key,
  email text not null,
  event_type text not null,
  result text not null default 'success',
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists admin_security_events_created_at_idx
  on public.admin_security_events (created_at desc);
create index if not exists admin_security_events_email_created_at_idx
  on public.admin_security_events (email, created_at desc);
alter table public.admin_security_events enable row level security;
revoke all on table public.admin_security_events from anon, authenticated;
grant select, insert, update, delete on table public.admin_security_events to service_role;
grant usage, select on sequence public.admin_security_events_id_seq to service_role;
comment on table public.admin_security_events is
  '중앙 관리자 보안 이벤트. 현재는 관리자 인증 성공 기록을 저장하며 비밀번호/토큰은 저장하지 않음.';
